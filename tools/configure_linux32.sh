#!/bin/sh
# Configure a 32-bit Linux build (the same pointer size as the PS1 and the Vita).
# HEADLESS=1 builds SDL3 without X11/Wayland/audio drivers (CI / containers).
set -e
BUILD=${BUILD:-build/linux32}
EXTRA=""
if [ "${HEADLESS:-0}" = 1 ]; then
    EXTRA="-DSDL_UNIX_CONSOLE_BUILD=ON -DSDL_X11=OFF -DSDL_WAYLAND=OFF -DSDL_PULSEAUDIO=OFF \
-DSDL_PIPEWIRE=OFF -DSDL_ALSA=OFF -DSDL_JACK=OFF -DSDL_SNDIO=OFF -DSDL_KMSDRM=OFF \
-DSDL_OPENGL=OFF -DSDL_OPENGLES=OFF -DSDL_VULKAN=OFF -DSDL_LIBUDEV=OFF -DSDL_DBUS=OFF \
-DSDL_IBUS=OFF -DSDL_HIDAPI_LIBUSB=OFF"
fi
cmake -S . -B "$BUILD" -G Ninja -DCMAKE_BUILD_TYPE=${TYPE:-RelWithDebInfo} \
    -DCMAKE_C_FLAGS=-m32 -DCMAKE_CXX_FLAGS=-m32 \
    -DCMAKE_EXE_LINKER_FLAGS=-m32 -DCMAKE_SHARED_LINKER_FLAGS=-m32 $EXTRA "$@"
