#!/usr/bin/env python3
"""Copy the C sources of one release of the Digimon World decomp into game/.

The decomp (external/dw_decomp, MIT) is the source of truth for the game logic.
The port keeps its own editable copy in game/ so native fixes can be made in
place, marked with DW1_NATIVE. Re-running this script overwrites game/ with the
upstream files, so commit (or stash) port changes first and re-apply them with
git (e.g. `git diff` before, `git apply` after).

Text (text/**/*.yaml) is NOT copied: it is turned into headers at build time by
the decomp's own tools/gen_text.py (see CMakeLists.txt).

Usage: tools/import_decomp.py [--version us]
"""

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECOMP = ROOT / "external" / "dw_decomp"
GAME = ROOT / "game"


def parse_units(version: str):
    """Return {unit_name: [c files]} from mk/version/<version>.mk."""
    mk = (DECOMP / "mk" / "version" / f"{version}.mk").read_text()
    mk = mk.replace("\\\n", " ")
    units = {}
    for m in re.finditer(r"^(\w+)_C_SRC\s*:=\s*(.*)$", mk, re.M):
        files = m.group(2).split()
        units[m.group(1).lower()] = files
    return units


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", default="us")
    args = ap.parse_args()

    if not (DECOMP / "Makefile").exists():
        sys.exit("external/dw_decomp is missing: git submodule update --init")

    units = parse_units(args.version)
    if not units:
        sys.exit(f"no C units found for version {args.version}")

    if GAME.exists():
        shutil.rmtree(GAME)

    # headers: the game's own include tree (no Sony SDK headers; PSY-Z provides those)
    for sub in ["dw", "common.h", "include_asm.h", "__rts_info_t__.h"]:
        src = DECOMP / "include" / sub
        dst = GAME / "include" / sub
        if src.is_dir():
            shutil.copytree(src, dst)
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)

    lines = []
    total = 0
    for unit, files in units.items():
        for f in files:
            src = DECOMP / f
            dst = GAME / f
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
            total += 1
        lines.append(f"set(DW1_{unit.upper()}_SRC")
        lines += [f"    game/{f}" for f in files]
        lines.append(")")

    lines.append("set(DW1_UNITS " + " ".join(u.upper() for u in units) + ")")
    (ROOT / "cmake").mkdir(exist_ok=True)
    (ROOT / "cmake" / f"sources_{args.version}.cmake").write_text(
        "# Generated by tools/import_decomp.py from external/dw_decomp/mk/version/"
        f"{args.version}.mk. Do not edit.\n" + "\n".join(lines) + "\n")

    print(f"imported {total} C files in {len(units)} units ({args.version}) into game/")


if __name__ == "__main__":
    main()
